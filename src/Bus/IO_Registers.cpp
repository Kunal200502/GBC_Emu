std::unordered_map<uint8_t, uint8_t> IO_Registers::openValues = {
    {0x00, 0xC0}, {0x01, 0x00}, {0x02, 0x7E}, {0x10, 0x80}, {0x0F, 0xE0}, 
    {0x1A, 0x7F}, {0x1C, 0x9F}, {0x20, 0xC0}, {0x23, 0x3F}, {0x26, 0x70}, 
    {0x41, 0x80}
};

IO_Registers::IO_Registers(){
    registers = std::vector<uint8_t>(0x80, 0xFF);
    for(auto it = initialValues.begin(); it != initialValues.end(); it++){
        registers[it->first] = it->second;
    }
}

uint8_t IO_Registers::read(uint16_t address){
    return registers[address];
}

void IO_Registers::write(uint16_t address, uint8_t value){
    auto it = openValues.find(address);
    if(it != openValues.end()){
        registers[address] = value | it->second;
    }else{
        registers[address] = value;
    }
}

IO_Registers_Snapshot IO_Registers::createSnapshot(){
    IO_Registers_Snapshot io_registers_snapshot(registers);
    return io_registers_snapshot;
}

void IO_Registers::restoreSnapshot(IO_Registers_Snapshot* snapshot){
    registers = snapshot->registers;
}